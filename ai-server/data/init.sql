-- ============================================================
-- 导出视图：合并为 Markdown 文本
-- ============================================================

-- 导出知识文章
SELECT CONCAT('# ', title, '\n\n', content) AS markdown
FROM knowledge_articles;

-- 导出传承人
SELECT CONCAT(
    '# ', name, '\n\n',
    CASE WHEN honor_title != '' THEN CONCAT('荣誉称号：', honor_title, '\n\n') ELSE '' END,
    CASE WHEN region != '' THEN CONCAT('地区：', region, '\n') ELSE '' END,
    CASE WHEN birth_year IS NOT NULL THEN CONCAT('出生：', birth_year, '年\n') ELSE '' END,
    '非遗项目：', craft, '\n\n',
    intro
) AS markdown
FROM inheritors;

-- 导出项目活动
SELECT CONCAT(
    '# ', title, '\n\n',
    '类别：', category, '\n',
    '地点：', location, '\n',
    CASE WHEN start_date IS NOT NULL THEN CONCAT('时间：', start_date, ' 至 ', end_date, '\n') ELSE '' END,
    CASE WHEN price > 0 THEN CONCAT('费用：¥', price, '\n') ELSE '费用：免费\n' END,
    CASE WHEN inheritor_name != '' THEN CONCAT('指导老师：', inheritor_name, '\n') ELSE '' END,
    '\n', description
) AS markdown
FROM heritage_projects WHERE status = 1;

-- 导出商品
SELECT CONCAT(
    '# ', name, '\n\n',
    '品类：', category, '\n',
    '价格：¥', price, '\n',
    CASE WHEN stock > 0 THEN CONCAT('库存：', stock, '件\n') ELSE '库存：缺货\n' END,
    CASE WHEN craft != '' THEN CONCAT('关联非遗：', craft, '\n') ELSE '' END,
    '\n', description
) AS markdown
FROM products WHERE status = 1;
